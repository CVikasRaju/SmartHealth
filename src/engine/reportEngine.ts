/** Build a tolerant regex for an alias so `Vitamin D (25-OH)` still matches. */
function aliasRegex(alias: string): RegExp {
  const parts = alias.split(" ").map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  return new RegExp(parts.join("[\\s().,\\-/]*"), "i");
}

/**
 * Try to read one raw OCR line as a biomarker result. The row shape assumed is
 * `test name | value | unit | reference range | flag`, which is what both the
 * synthetic transcripts and real analyser printouts use.
 */
export function matchBiomarkerLine(raw: string): ExtractedField | null {
  const line = normaliseLine(raw);
  if (line.length < 4) return null;

  const haystack = matchForm(line);

  for (const { alias, needle, definition } of ALIAS_INDEX) {
    if (!containsAlias(haystack, needle)) continue;

    // Step 1: strip the test name so digits inside it (the "25" of
    // "25-OH Vitamin D", the "3" of "T3") cannot be read as the result.
    const stripped = line.replace(aliasRegex(alias), " ");

    // Step 2: cut at the reference-range column, which prints as two numbers
    // joined by a dash or the word "to".
    const rangeMatch = stripped.match(/\d+(?:\.\d+)?\s*(?:-|to)\s*\d+(?:\.\d+)?/i);
    const head =
      rangeMatch && rangeMatch.index !== undefined ? stripped.slice(0, rangeMatch.index) : stripped;

    // Step 3: drop unit glyphs, including exponent forms such as "x10^3/uL",
    // which would otherwise leave stray digits behind.
    const cleaned = head.replace(new RegExp(UNIT_PATTERN.source, "gi"), " ");

    const tokens = cleaned.match(new RegExp(NUMBER_PATTERN.source, "g"));
    if (!tokens || tokens.length === 0) continue;

    // Step 4: the last surviving number on the row is the reported result.
    const rawToken = tokens[tokens.length - 1];
    const value = toNumber(rawToken);
    if (value === null) continue;

    const unitMatch = line.match(UNIT_PATTERN);
    const unit = unitMatch ? canonicalUnit(unitMatch[1]) : definition.unit;
    const referenceRange = toReferenceRange(definition);
    const status = scoreBiomarkerStatus(value, referenceRange);

    let confidence = 0.7;
    if (unitMatch) confidence += 0.16;
    if (rangeMatch) confidence += 0.07;
    if (line.length < 12) confidence -= 0.12;
    if (unit === definition.unit) confidence += 0.05;
    // Deterministic per-line jitter keeps repeated values from looking identical.
    confidence += ((hashString(line) % 9) - 4) / 100;
    confidence = Math.min(0.99, Math.max(0.31, Number(confidence.toFixed(2))));

    return {
      id: `field-${hashString(`${definition.key}:${line}`).toString(36)}`,
      testName: definition.displayName,
      normalizedKey: definition.key,
      value,
      valueText: rawToken,
      unit,
      referenceRange,
      status,
      plainLanguageExplanation: buildExplanation(definition, value, unit, status),
      category: definition.category,
      confidence,
      matchedAlias: alias,
    };
  }

  return null;
}

/**
 * Extract every recognisable biomarker from a blob of OCR text. Duplicate
 * mentions keep the highest-confidence reading, mirroring how a human would
 * take the printed result column over a value repeated in a summary footer.
 */
export function parseReportText(text: string): ExtractedField[] {
  const byKey = new Map<string, ExtractedField>();

  for (const rawLine of text.split(/\r?\n/)) {
    const field = matchBiomarkerLine(rawLine);
    if (!field) continue;
    const existing = byKey.get(field.normalizedKey);
    if (!existing || field.confidence > existing.confidence) {
      byKey.set(field.normalizedKey, field);
    }
  }

  // Preserve dictionary order so panels read the way a lab prints them.
  return BIOMARKER_DICTIONARY.filter((definition) => byKey.has(definition.key)).map(
    (definition) => byKey.get(definition.key) as ExtractedField,
  );
}

