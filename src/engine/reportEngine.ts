export interface ReportSummary {
  total: number;
  inRange: number;
  outOfRange: number;
  critical: number;
  /** One-line, non-diagnostic headline for the summary card. */
  headline: string;
}

export function summariseFields(fields: ExtractedField[]): ReportSummary {
  const critical = fields.filter(
    (field) => field.status === "critical_low" || field.status === "critical_high",
  ).length;
  const outOfRange = fields.filter((field) => isOutOfRange(field.status)).length;
  const total = fields.length;

  let headline: string;
  if (total === 0) {
    headline = "No recognised lab values were found in this document.";
  } else if (critical > 0) {
    headline =
      `${critical} value${critical === 1 ? "" : "s"} sit well outside the reference range. ` +
      "Show this report to your treating physician for review.";
  } else if (outOfRange > 0) {
    headline =
      `${outOfRange} of ${total} values sit outside the reference range. ` +
      "Outside-range results are common and are always read alongside your history.";
  } else {
    headline = `All ${total} recognised values fall inside their reference ranges.`;
  }

  return { total, inRange: total - outOfRange, outOfRange, critical, headline };
}

