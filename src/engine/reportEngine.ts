/**
 * Matching index. Aliases are sorted longest-first so `hba1c` wins over `hb` on
 * the same line, and each entry keeps both the raw alias (used to strip the
 * test name off the raw line) and the normalised needle (used to test a line).
 */
const ALIAS_INDEX: { alias: string; needle: string; definition: BiomarkerDefinition }[] =
  BIOMARKER_DICTIONARY.flatMap((definition) =>
    definition.aliases.map((alias) => ({ alias, needle: matchForm(alias), definition })),
  ).sort((a, b) => b.needle.length - a.needle.length);

export function findBiomarkerDefinition(key: string): BiomarkerDefinition | undefined {
  return BIOMARKER_DICTIONARY.find((definition) => definition.key === key);
}

