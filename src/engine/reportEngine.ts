/** Fold the unicode noise that OCR engines emit into plain ASCII. */
export function normaliseLine(raw: string): string {
  return raw
    .replace(/[\u2212\u2013\u2014]/g, "-")
    .replace(/[\u00b5\u03bc]/g, "µ")
    .replace(/\u00d7/g, "x")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Lowercased, punctuation-free form used for dictionary matching. Hyphens and
 * slashes become spaces so `C-Reactive Protein` and `c reactive protein` are
 * the same needle.
 */
function matchForm(raw: string): string {
  return normaliseLine(raw)
    .toLowerCase()
    .replace(/[():,;/\\-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

