/**
 * Map every recognised spelling of a unit onto its single display form, so the
 * extracted field and its reference range always render the same unit.
 */
export function canonicalUnit(raw: string): string {
  const key = normaliseLine(raw).toLowerCase().replace(/\s+/g, "");
  return UNIT_ALIASES[key] ?? normaliseLine(raw);
}

function toNumber(token: string): number | null {
  const cleaned = token.replace(/,(\d{1,2})$/, ".$1").replace(/,/g, "");
  const parsed = Number(cleaned);
  return Number.isFinite(parsed) ? parsed : null;
}

/** Deterministic 32-bit hash so confidence values are stable across reloads. */
function hashString(value: string): number {
  let hash = 2166136261;
  for (let i = 0; i < value.length; i++) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

/** Word-boundary safe test: `hb` must not match inside `hba1c`. */
function containsAlias(haystack: string, alias: string): boolean {
  let from = 0;
  for (;;) {
    const index = haystack.indexOf(alias, from);
    if (index === -1) return false;
    const before = index === 0 ? "" : haystack[index - 1];
    const after = index + alias.length >= haystack.length ? "" : haystack[index + alias.length];
    const boundary = (char: string) => char === "" || char === " " || char === "-" || char === "/";
    if (boundary(before) && boundary(after)) return true;
    from = index + 1;
  }
}

/* ------------------------------------------------------------------ */
/* Reference range scoring                                             */
/* ------------------------------------------------------------------ */

export function referenceRangeText(min: number, max: number, unit: string): string {
  const format = (value: number) => String(value);
  return `${format(min)} - ${format(max)} ${unit}`.trim();
}

export function toReferenceRange(definition: BiomarkerDefinition): ReferenceRange {
  return {
    min: definition.min,
    max: definition.max,
    text: referenceRangeText(definition.min, definition.max, definition.unit),
    criticalLow: definition.criticalLow,
    criticalHigh: definition.criticalHigh,
  };
}

/** Classify a value against its range and optional panic thresholds. */
export function scoreBiomarkerStatus(value: number, range: ReferenceRange): BiomarkerStatus {
  if (!Number.isFinite(value)) return "unknown";
  if (range.criticalHigh !== undefined && value >= range.criticalHigh) return "critical_high";
  if (range.criticalLow !== undefined && value <= range.criticalLow) return "critical_low";
  if (value > range.max) return "elevated";
  if (value < range.min) return "low";
  return "normal";
}

export function isOutOfRange(status: BiomarkerStatus): boolean {
  return status === "low" || status === "elevated" || status === "critical_low" || status === "critical_high";
}

/** Build the non-diagnostic plain-language explanation for one result. */
