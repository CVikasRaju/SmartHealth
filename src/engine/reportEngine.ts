/**
 * Build per-biomarker history for one patient. Reports are sorted oldest-first
 * so the resulting series is directly chartable, and `previous` always refers
 * to the reading before the latest one.
 */
export function buildTrendSeries(
  reports: MedicalReport[],
  patientId: string,
  filterKeys?: string[],
): BiomarkerTrend[] {
  const relevant = reports
    .filter((report) => report.patientId === patientId)
    .slice()
    .sort((a, b) => new Date(a.reportDate).getTime() - new Date(b.reportDate).getTime());

  const series = new Map<string, BiomarkerTrend>();

  for (const report of relevant) {
    for (const field of report.extractedFields) {
      if (!field.normalizedKey) continue;
      if (filterKeys && filterKeys.length > 0 && !filterKeys.includes(field.normalizedKey)) continue;

      const point: TrendPoint = {
        date: report.reportDate,
        value: field.value,
        reportId: report.id,
      };

      const existing = series.get(field.normalizedKey);
      if (existing) {
        // A single report should contribute one point per biomarker; if the
        // same key repeats within one panel, the last reading wins.
        const last = existing.history[existing.history.length - 1];
        if (last && last.reportId === report.id) {
          existing.history[existing.history.length - 1] = point;
        } else {
          existing.history.push(point);
        }
        existing.latest = point.value;
        existing.status = field.status;
        existing.unit = field.unit;
        existing.plainLanguageExplanation = field.plainLanguageExplanation;
        continue;
      }

      series.set(field.normalizedKey, {
        normalizedKey: field.normalizedKey,
        testName: field.testName,
        unit: field.unit,
        category: field.category,
        referenceRange: field.referenceRange,
        history: [point],
        latest: point.value,
        previous: null,
        delta: null,
        deltaPct: null,
        direction: "stable",
        status: field.status,
        plainLanguageExplanation: field.plainLanguageExplanation,
      });
    }
  }

  for (const trend of series.values()) {
    const history = trend.history;
    if (history.length >= 2) {
      const latest = history[history.length - 1].value;
      const previous = history[history.length - 2].value;
      trend.previous = previous;
      trend.delta = Number((latest - previous).toFixed(2));
      trend.deltaPct = previous === 0 ? null : Number((((latest - previous) / previous) * 100).toFixed(1));
      trend.direction = classifyDirection(latest, previous, trend.referenceRange);
    }
  }

  return Array.from(series.values()).sort((a, b) => a.testName.localeCompare(b.testName));
}

/**
 * Direction of travel compared with the reference range. A change of less than
 * 2% of the range width is treated as stable so chart noise is not narrated.
 */
export function classifyDirection(
  latest: number,
  previous: number,
  range: ReferenceRange,
): "rising" | "falling" | "stable" {
  const width = Math.max(range.max - range.min, 1);
  const threshold = width * 0.02;
  const delta = latest - previous;
  if (Math.abs(delta) < threshold) return "stable";
  return delta > 0 ? "rising" : "falling";
}

/** Non-diagnostic narrative describing the direction of a trend. */
export function describeTrend(trend: BiomarkerTrend): string {
  if (trend.history.length < 2) {
    return "This is the first recorded result for this biomarker, so no comparison is available yet.";
  }
  const width = Math.max(trend.referenceRange.max - trend.referenceRange.min, 1);
  const changePct = Math.abs(((trend.latest - (trend.previous ?? trend.latest)) / width) * 100).toFixed(0);

  if (trend.direction === "stable") {
    return `The last ${trend.history.length} readings have stayed broadly level, moving less than ${
      trend.referenceRange.max === trend.referenceRange.min ? "the range width" : `${changePct}% of the reference range width`
    } between visits.`;
  }

  if (trend.direction === "rising") {
    return `Across the last ${trend.history.length} readings this value has moved upward, most recently by ${changePct}% of the reference range width. Direction of travel is not a diagnosis.`;
  }

  return `Across the last ${trend.history.length} readings this value has moved downward, most recently by ${changePct}% of the reference range width. Direction of travel is not a diagnosis.`;
}

/** Group extracted fields by panel category for the report screen sections. */
export function groupFieldsByCategory(fields: ExtractedField[]): { category: BiomarkerCategory; fields: ExtractedField[] }[] {
  const groups = new Map<BiomarkerCategory, ExtractedField[]>();
  for (const field of fields) {
    const list = groups.get(field.category) ?? [];
    list.push(field);
    groups.set(field.category, list);
  }
  return Array.from(groups.entries()).map(([category, grouped]) => ({ category, fields: grouped }));
}

