export const OCR_PIPELINE_STEPS = [
  "Pre-processing scan (binarisation, deskew, denoise)",
  "Running optical character recognition",
  "Matching biomarker dictionary aliases",
  "Normalising units and reference ranges",
] as const;

function wait(ms: number): Promise<void> {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

/** True when the browser can hand us the file's own text content. */
function isTextLike(fileName: string, mimeType: string): boolean {
  return /\.(txt|csv)$/i.test(fileName) || mimeType.startsWith("text/");
}

/**
 * Simulated OCR run. Reads real text when the file already contains it and
 * otherwise falls back to the synthetic transcript for the selected panel.
 */
export async function runSimulatedOcr(
  file: File,
  category: ReportCategory,
  onProgress?: (event: OcrProgressEvent) => void,
): Promise<OcrResult> {
  let directText: string | null = null;

  if (isTextLike(file.name, file.type)) {
    directText = await file.text();
  }

  for (let index = 0; index < OCR_PIPELINE_STEPS.length; index++) {
    onProgress?.({ ratio: index / OCR_PIPELINE_STEPS.length, step: OCR_PIPELINE_STEPS[index] });
    // A short, visible delay so the pipeline stages are legible in the demo.
    await wait(260);
  }

  onProgress?.({ ratio: 1, step: "Extraction complete" });

  if (directText && directText.trim().length > 0) {
    const fields = parseReportText(directText);
    const confidence = fields.length
      ? Number((fields.reduce((sum, field) => sum + field.confidence, 0) / fields.length).toFixed(2))
      : 0.4;
    return { text: directText, confidence, engine: "direct-text" };
  }

  const text = SYNTHETIC_OCR_TRANSCRIPTS[category];
  const fields = parseReportText(text);
  const confidence = fields.length
    ? Number((fields.reduce((sum, field) => sum + field.confidence, 0) / fields.length).toFixed(2))
    : 0.4;
  return { text, confidence, engine: "simulated" };
}

